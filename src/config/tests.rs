use super::*;
use std::io::Write;
use tempfile::NamedTempFile;

#[test]
fn test_read_config_valid_file() -> Result<()> {
    let mut tmpfile = NamedTempFile::new()?;
    write!(
        tmpfile,
        r#"mpi_pdf: "mpi31-report.pdf"
output_file: "test_wrapper.c"
templates:
  header: "generated by mpi_wrap_gen"
  ch_init: "chapter: {{chapter}}"
  ch_decl: "function declaration: {{chapter}}"
  ch_load_imb: "load imbalance: {{chapter}}"
  ch_body: "MPI function"
  bar_init: "barrier chapter: {{chapter}}"
  bar_body: "barrier MPI function"
  footer: "end of the file"
chapters:
  - 3
  - 4
  - 5
excludes:
  - "MPI_Init"
  - "MPI_Finalize"
"#
    )?;
    let path = tmpfile.path().to_string_lossy();

    let config = read_config(path.as_ref())?;
    assert_eq!(config.mpi_pdf, std::path::PathBuf::from("mpi31-report.pdf"));
    assert_eq!(
        config.output_file,
        std::path::PathBuf::from("test_wrapper.c")
    );
    assert!(config
        .templates
        .header
        .contains("generated by mpi_wrap_gen"));
    assert!(config.templates.ch_init.contains("{chapter}"));
    assert!(config.templates.ch_decl.contains("{chapter}"));
    assert!(config
        .templates
        .ch_load_imb
        .contains("imbalance: {chapter}"));
    assert!(config.templates.ch_body.contains("MPI function"));
    assert!(config.templates.bar_init.contains("{chapter}"));
    assert!(config.templates.bar_body.contains("barrier MPI function"));
    assert!(config.templates.footer.contains("end of the file"));
    assert_eq!(config.chapters, vec![3, 4, 5]);
    assert_eq!(config.excludes, vec!["MPI_Init", "MPI_Finalize"]);
    Ok(())
}

